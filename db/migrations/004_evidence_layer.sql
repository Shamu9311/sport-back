-- 004_evidence_layer.sql
-- Capa de evidencia científica (solo esquema; aún no la usa el código).
-- evidence_sources  : paper, consenso, posición oficial, regulatorio...
-- evidence_chunks   : fragmentos recuperables con embedding vector(768)
-- evidence_claims   : afirmaciones estructuradas extraídas de una fuente/fragmento
-- product_evidence  : vínculo producto ↔ claim/fuente

CREATE TABLE evidence_sources (
  source_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_type    text NOT NULL CHECK (source_type IN ('paper','meta_analisis','revision_sistematica','consenso',
                                                      'posicion_oficial','regulatorio','guia')),
  title          text NOT NULL,
  authors        text,
  organization   text,
  journal        text,
  year           smallint CHECK (year BETWEEN 1900 AND 2100),
  doi            varchar(255),
  pmid           varchar(20),
  url            text,
  evidence_level text CHECK (evidence_level IN ('A','B','C','D')),
  license        varchar(100),
  language       char(2) DEFAULT 'en',
  status         text NOT NULL DEFAULT 'borrador' CHECK (status IN ('borrador','revisado','retirado')),
  reviewed_by    varchar(255),
  reviewed_at    timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz
);
CREATE UNIQUE INDEX evidence_sources_doi_key ON evidence_sources (lower(doi)) WHERE doi IS NOT NULL;
CREATE UNIQUE INDEX evidence_sources_pmid_key ON evidence_sources (pmid) WHERE pmid IS NOT NULL;
CREATE INDEX evidence_sources_status_idx ON evidence_sources (status);
CREATE TRIGGER evidence_sources_set_updated_at
  BEFORE UPDATE ON evidence_sources
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE evidence_chunks (
  chunk_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id       integer NOT NULL REFERENCES evidence_sources (source_id) ON DELETE CASCADE,
  chunk_index     integer NOT NULL,
  section         varchar(100),
  content         text NOT NULL,
  token_count     integer,
  content_hash    char(64) NOT NULL,
  embedding       extensions.vector(768),
  embedding_model varchar(50),
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz,
  CONSTRAINT evidence_chunks_source_index_key UNIQUE (source_id, chunk_index),
  CONSTRAINT evidence_chunks_content_hash_key UNIQUE (content_hash),
  CONSTRAINT evidence_chunks_nonzero CHECK (embedding IS NULL OR extensions.vector_norm(embedding) > 0)
);
CREATE INDEX evidence_chunks_source_id_idx ON evidence_chunks (source_id);
CREATE INDEX evidence_chunks_embedding_hnsw_idx
  ON evidence_chunks USING hnsw (embedding extensions.vector_cosine_ops);
CREATE TRIGGER evidence_chunks_set_updated_at
  BEFORE UPDATE ON evidence_chunks
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE evidence_claims (
  claim_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id   integer NOT NULL REFERENCES evidence_sources (source_id) ON DELETE CASCADE,
  chunk_id    integer REFERENCES evidence_chunks (chunk_id) ON DELETE SET NULL,
  ingredient  varchar(100),
  outcome     varchar(150),
  effect      text CHECK (effect IN ('beneficio','sin_efecto','riesgo','mixto')),
  population  varchar(150),
  dose_text   varchar(150),
  timing      text CHECK (timing IN ('antes','durante','despues','diario')),
  claim_text  text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX evidence_claims_source_id_idx ON evidence_claims (source_id);
CREATE INDEX evidence_claims_chunk_id_idx ON evidence_claims (chunk_id);
CREATE INDEX evidence_claims_ingredient_idx ON evidence_claims (lower(ingredient));

CREATE TABLE product_evidence (
  product_evidence_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id          integer NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
  source_id           integer REFERENCES evidence_sources (source_id) ON DELETE CASCADE,
  claim_id            integer REFERENCES evidence_claims (claim_id) ON DELETE CASCADE,
  relevance           numeric(4,3) CHECK (relevance BETWEEN 0 AND 1),
  notes               text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT product_evidence_target_chk CHECK (source_id IS NOT NULL OR claim_id IS NOT NULL)
);
CREATE UNIQUE INDEX product_evidence_unique_idx
  ON product_evidence (product_id, COALESCE(source_id, 0), COALESCE(claim_id, 0));
CREATE INDEX product_evidence_source_id_idx ON product_evidence (source_id);
CREATE INDEX product_evidence_claim_id_idx ON product_evidence (claim_id);
