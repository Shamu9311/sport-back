-- ------------------------------------------------------------------ Reglas entre tablas (triggers)

-- Claims: una especificación del fabricante solo aporta composición e instrucciones (nunca eficacia/seguridad)
CREATE OR REPLACE FUNCTION public.evidence_claims_rules() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  v_category text;
BEGIN
  SELECT source_category INTO v_category FROM evidence_sources WHERE source_id = NEW.source_id;
  IF v_category = 'manufacturer_specification'
     AND NEW.claim_type NOT IN ('composition','usage_instruction') THEN
    RAISE EXCEPTION 'Una especificación del fabricante no puede aportar claims de tipo % (solo composition/usage_instruction)', NEW.claim_type
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER evidence_claims_rules_trg BEFORE INSERT OR UPDATE ON evidence_claims
  FOR EACH ROW EXECUTE FUNCTION public.evidence_claims_rules();

-- Claim ↔ chunk: ambos deben pertenecer a la misma fuente
CREATE OR REPLACE FUNCTION public.evidence_claim_chunks_rules() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
BEGIN
  IF (SELECT source_id FROM evidence_claims WHERE claim_id = NEW.claim_id)
     IS DISTINCT FROM (SELECT source_id FROM evidence_chunks WHERE chunk_id = NEW.chunk_id) THEN
    RAISE EXCEPTION 'El claim % y el chunk % pertenecen a fuentes distintas', NEW.claim_id, NEW.chunk_id
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER evidence_claim_chunks_rules_trg BEFORE INSERT OR UPDATE ON evidence_claim_chunks
  FOR EACH ROW EXECUTE FUNCTION public.evidence_claim_chunks_rules();

-- Producto ↔ evidencia: la relación debe estar justificada por los datos (conserva el grado de indirección)
CREATE OR REPLACE FUNCTION public.product_evidence_rules() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  v_claim record;
  v_category text;
BEGIN
  SELECT source_category INTO v_category FROM evidence_sources WHERE source_id = NEW.source_id;

  IF NEW.claim_id IS NOT NULL THEN
    SELECT * INTO v_claim FROM evidence_claims WHERE claim_id = NEW.claim_id;
    IF v_claim.source_id <> NEW.source_id THEN
      RAISE EXCEPTION 'El claim % no pertenece a la fuente %', NEW.claim_id, NEW.source_id USING ERRCODE = 'check_violation';
    END IF;
  END IF;

  IF NEW.relation_type = 'direct_product' THEN
    IF NOT v_claim.product_specific OR v_claim.product_id IS DISTINCT FROM NEW.product_id THEN
      RAISE EXCEPTION 'direct_product exige un claim que estudie específicamente el producto %', NEW.product_id
        USING ERRCODE = 'check_violation';
    END IF;
    IF v_category = 'manufacturer_specification' THEN
      RAISE EXCEPTION 'Una especificación del fabricante se relaciona como manufacturer_specification, no como direct_product'
        USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.relation_type = 'manufacturer_specification' THEN
    IF v_category <> 'manufacturer_specification' THEN
      RAISE EXCEPTION 'manufacturer_specification exige una fuente de categoría manufacturer_specification'
        USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.relation_type = 'ingredient' THEN
    IF NOT EXISTS (SELECT 1 FROM product_ingredients
                   WHERE product_id = NEW.product_id AND ingredient_id = NEW.ingredient_id) THEN
      RAISE EXCEPTION 'El producto % no contiene el ingrediente % (product_ingredients)', NEW.product_id, NEW.ingredient_id
        USING ERRCODE = 'check_violation';
    END IF;
    IF v_claim.claim_id IS NOT NULL AND v_claim.ingredient_id IS DISTINCT FROM NEW.ingredient_id THEN
      RAISE EXCEPTION 'El ingrediente de la relación no coincide con el del claim' USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.relation_type = 'formulation' THEN
    IF NOT EXISTS (SELECT 1 FROM product_formulations
                   WHERE product_id = NEW.product_id AND formulation_id = NEW.formulation_id) THEN
      RAISE EXCEPTION 'El producto % no tiene la formulación % (product_formulations)', NEW.product_id, NEW.formulation_id
        USING ERRCODE = 'check_violation';
    END IF;
  ELSIF NEW.relation_type = 'category' THEN
    IF NOT EXISTS (SELECT 1 FROM products p JOIN product_types pt ON pt.type_id = p.type_id
                   WHERE p.product_id = NEW.product_id AND pt.category_id = NEW.category_id) THEN
      RAISE EXCEPTION 'El producto % no pertenece a la categoría %', NEW.product_id, NEW.category_id
        USING ERRCODE = 'check_violation';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER product_evidence_rules_trg BEFORE INSERT OR UPDATE ON product_evidence
  FOR EACH ROW EXECUTE FUNCTION public.product_evidence_rules();
