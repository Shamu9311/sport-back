-- 009_evidence_model_v2.sql
-- Rediseño de la capa de evidencia científica. Las 4 tablas de la migración 004 estaban VACÍAS
-- (verificado en BD principal y de test), por lo que se recrean en lugar de alterarse.
-- La capa NO participa todavía en las recomendaciones (USE_EVIDENCE_RAG=false).

DROP TABLE IF EXISTS product_evidence, evidence_claims, evidence_chunks, evidence_sources CASCADE;

-- ------------------------------------------------------------------ Fuentes
CREATE TABLE evidence_sources (
  source_id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_key       varchar(120) NOT NULL UNIQUE CHECK (source_key ~ '^[a-z0-9][a-z0-9_.-]*$'),
  source_type      text NOT NULL CHECK (source_type IN (
                     'meta_analysis','systematic_review','randomized_controlled_trial','crossover_trial',
                     'non_randomized_trial','observational_study','narrative_review',
                     'consensus','position_stand','guideline','official_framework',
                     'manufacturer_specification','other')),
  -- Derivada del tipo (no editable): separa evidencia científica / guía oficial / fabricante
  source_category  text GENERATED ALWAYS AS (CASE
                     WHEN source_type IN ('consensus','position_stand','guideline','official_framework') THEN 'official_guideline'
                     WHEN source_type = 'manufacturer_specification' THEN 'manufacturer_specification'
                     ELSE 'scientific_evidence' END) STORED,
  title            text NOT NULL CHECK (length(btrim(title)) > 0),
  authors          text[] NOT NULL DEFAULT '{}',
  organization     text,
  journal          text,
  year             smallint CHECK (year BETWEEN 1900 AND 2100),
  publication_date date,
  accessed_date    date,
  doi              varchar(255) CHECK (doi IS NULL OR doi ~ '^10\.[0-9]{4,9}/\S+$'),
  pmid             varchar(20)  CHECK (pmid IS NULL OR pmid ~ '^[0-9]{1,9}$'),
  url              text,
  open_access      boolean,
  license          varchar(100),
  peer_reviewed    boolean,
  evidence_level   text CHECK (evidence_level IN ('A','B','C','D')),
  evidence_level_rationale text,
  funding          text,
  industry_funded  boolean,
  conflict_of_interest text,
  review_status    text NOT NULL DEFAULT 'draft' CHECK (review_status IN ('draft','reviewed','retired')),
  reviewed_by      varchar(255),
  reviewed_at      timestamptz,
  notes            text,
  language         char(2) DEFAULT 'en',
  manifest_sha256  char(64),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz,
  -- Toda fuente debe ser localizable; una fuente sin DOI (consensos, AIS) es válida con URL
  CONSTRAINT evidence_sources_locatable CHECK (doi IS NOT NULL OR pmid IS NOT NULL OR url IS NOT NULL),
  -- Fabricante: nivel NULL (recomendado) o D; nunca A–C
  CONSTRAINT evidence_sources_manufacturer_level CHECK (
    source_type <> 'manufacturer_specification' OR evidence_level IS NULL OR evidence_level = 'D'),
  -- Ajuste 2: el nivel A–D es obligatorio al revisar SOLO para evidencia científica y guías oficiales
  CONSTRAINT evidence_sources_reviewed_level CHECK (
    review_status <> 'reviewed' OR source_type = 'manufacturer_specification' OR evidence_level IS NOT NULL)
);
COMMENT ON COLUMN evidence_sources.evidence_level IS
  'Calidad de la fuente (escala operativa A–D propia de esta investigación; no es GRADE). Ver data/evidence/README.md';
CREATE UNIQUE INDEX evidence_sources_doi_key  ON evidence_sources (lower(doi)) WHERE doi IS NOT NULL;
CREATE UNIQUE INDEX evidence_sources_pmid_key ON evidence_sources (pmid) WHERE pmid IS NOT NULL;
CREATE INDEX evidence_sources_status_idx ON evidence_sources (review_status, source_category);
CREATE TRIGGER evidence_sources_set_updated_at BEFORE UPDATE ON evidence_sources
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ------------------------------------------------------------------ Fragmentos (chunks)
CREATE TABLE evidence_chunks (
  chunk_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id        integer NOT NULL REFERENCES evidence_sources (source_id) ON DELETE CASCADE,
  chunk_key        varchar(140) NOT NULL CHECK (chunk_key ~ '^[a-z0-9][a-z0-9_.-]*$'),
  chunk_index      integer NOT NULL CHECK (chunk_index >= 0),
  section          text NOT NULL CHECK (section IN ('abstract','introduction','methods','results','discussion',
                     'conclusion','recommendation','table','summary','product_information','other')),
  heading          text,
  page             varchar(20),
  paragraph        varchar(20),
  content          text NOT NULL CHECK (length(btrim(content)) > 0),
  content_kind     text NOT NULL DEFAULT 'excerpt' CHECK (content_kind IN ('verbatim','excerpt','own_summary')),
  content_hash     char(64) NOT NULL,
  token_count      integer,
  embedding        extensions.vector(768),
  embedding_model  varchar(60),
  embedded_content_hash char(64),
  embedded_at      timestamptz,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz,
  UNIQUE (source_id, chunk_key),
  UNIQUE (source_id, chunk_index) DEFERRABLE INITIALLY DEFERRED,
  UNIQUE (source_id, content_hash),
  CONSTRAINT evidence_chunks_nonzero CHECK (embedding IS NULL OR extensions.vector_norm(embedding) > 0),
  CONSTRAINT evidence_chunks_embedding_model CHECK ((embedding IS NULL) = (embedding_model IS NULL))
);
CREATE INDEX evidence_chunks_source_idx ON evidence_chunks (source_id);
CREATE INDEX evidence_chunks_embedding_hnsw_idx
  ON evidence_chunks USING hnsw (embedding extensions.vector_cosine_ops);
CREATE TRIGGER evidence_chunks_set_updated_at BEFORE UPDATE ON evidence_chunks
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- ------------------------------------------------------------------ Claims estructurados
CREATE TABLE evidence_claims (
  claim_id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_id        integer NOT NULL REFERENCES evidence_sources (source_id) ON DELETE CASCADE,
  claim_key        varchar(140) NOT NULL CHECK (claim_key ~ '^[a-z0-9][a-z0-9_.-]*$'),
  claim_type       text NOT NULL CHECK (claim_type IN ('efficacy','safety','dosage_guideline','timing_guideline',
                     'composition','usage_instruction','mechanism')),
  ingredient_id    integer REFERENCES ingredients (ingredient_id),
  ingredient_name_raw text,
  formulation_id   integer REFERENCES formulations (formulation_id),
  product_specific boolean NOT NULL DEFAULT false,
  product_id       integer REFERENCES products (product_id),
  population       text,
  sample_size      integer CHECK (sample_size IS NULL OR sample_size > 0),
  sex              text CHECK (sex IN ('male','female','mixed','not_reported')),
  training_status  text CHECK (training_status IN ('untrained','recreationally_active','trained','well_trained',
                     'elite','mixed','not_reported')),
  sport            text,
  exercise_context text,
  exercise_duration text,
  exercise_duration_min_minutes integer CHECK (exercise_duration_min_minutes IS NULL OR exercise_duration_min_minutes >= 0),
  exercise_duration_max_minutes integer CHECK (exercise_duration_max_minutes IS NULL OR exercise_duration_max_minutes >= 0),
  dose_text        text,
  dose_value       numeric CHECK (dose_value IS NULL OR dose_value >= 0),
  dose_value_max   numeric CHECK (dose_value_max IS NULL OR dose_value_max >= 0),
  dose_unit        text,
  dose_relative    text,
  frequency        text,
  duration_protocol text,
  timing_context   text[] NOT NULL DEFAULT '{not_specified}',
  timing_details   text,
  timing_evidence_strength text NOT NULL DEFAULT 'not_assessed'
                     CHECK (timing_evidence_strength IN ('strong','moderate','limited','not_assessed')),
  conditions       jsonb NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(conditions) = 'object'),
  outcome          text,
  effect_direction text NOT NULL CHECK (effect_direction IN (
                     'positive','neutral','negative','mixed','insufficient','not_applicable')),
  effect_size      text,
  effect_size_value numeric,
  effect_size_metric text,
  statistical_significance text NOT NULL DEFAULT 'not_reported'
                     CHECK (statistical_significance IN ('significant','not_significant','not_tested','not_reported')),
  result_summary   text NOT NULL CHECK (length(btrim(result_summary)) > 0),
  practical_interpretation text,
  limitations      text,
  evidence_strength text CHECK (evidence_strength IN ('A','B','C','D')),
  conflict_of_interest_notes text,
  review_status    text NOT NULL DEFAULT 'draft' CHECK (review_status IN ('draft','reviewed','retired')),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz,
  UNIQUE (source_id, claim_key),
  CONSTRAINT evidence_claims_timing_values CHECK (
    cardinality(timing_context) > 0
    AND timing_context <@ ARRAY['pre','during','post','daily_chronic','flexible','not_specified']::text[]),
  CONSTRAINT evidence_claims_subject CHECK (
    ingredient_id IS NOT NULL OR formulation_id IS NOT NULL OR product_id IS NOT NULL
    OR claim_type IN ('dosage_guideline','timing_guideline')),
  CONSTRAINT evidence_claims_product_specific CHECK (NOT product_specific OR product_id IS NOT NULL),
  CONSTRAINT evidence_claims_duration_range CHECK (
    exercise_duration_max_minutes IS NULL OR exercise_duration_min_minutes IS NULL
    OR exercise_duration_max_minutes >= exercise_duration_min_minutes),
  CONSTRAINT evidence_claims_dose_range CHECK (dose_value_max IS NULL OR dose_value IS NULL OR dose_value_max >= dose_value),
  -- Ajuste 1: not_applicable solo para claims que NO evalúan eficacia/seguridad, y obligatorio en composición/instrucciones
  CONSTRAINT evidence_claims_not_applicable_usage CHECK (
    (claim_type IN ('composition','usage_instruction')) = (effect_direction = 'not_applicable')),
  -- La ausencia de significancia NO es evidencia negativa
  CONSTRAINT evidence_claims_negative_needs_effect CHECK (
    NOT (effect_direction = 'negative' AND statistical_significance = 'not_significant')),
  -- Eficacia y seguridad requieren el resultado evaluado
  CONSTRAINT evidence_claims_outcome_required CHECK (claim_type NOT IN ('efficacy','safety') OR outcome IS NOT NULL)
);
COMMENT ON COLUMN evidence_claims.evidence_strength IS 'Fuerza del claim (puede ser menor que el nivel de la fuente).';
COMMENT ON COLUMN evidence_claims.timing_evidence_strength IS
  'Respaldo del MOMENTO de consumo. Fase futura: strong/moderate pueden justificar un timing; limited y not_assessed NO generan elegibilidad.';
CREATE INDEX evidence_claims_source_idx ON evidence_claims (source_id);
CREATE INDEX evidence_claims_ingredient_idx ON evidence_claims (ingredient_id);
CREATE INDEX evidence_claims_formulation_idx ON evidence_claims (formulation_id);
CREATE INDEX evidence_claims_product_idx ON evidence_claims (product_id);
CREATE INDEX evidence_claims_timing_gin ON evidence_claims USING gin (timing_context);
CREATE TRIGGER evidence_claims_set_updated_at BEFORE UPDATE ON evidence_claims
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

-- Claim ↔ chunks (procedencia del claim dentro de la fuente)
CREATE TABLE evidence_claim_chunks (
  claim_id integer NOT NULL REFERENCES evidence_claims (claim_id) ON DELETE CASCADE,
  chunk_id integer NOT NULL REFERENCES evidence_chunks (chunk_id) ON DELETE CASCADE,
  PRIMARY KEY (claim_id, chunk_id)
);
CREATE INDEX evidence_claim_chunks_chunk_idx ON evidence_claim_chunks (chunk_id);

-- ------------------------------------------------------------------ Evidencia ↔ producto
CREATE TABLE product_evidence (
  product_evidence_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     integer NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
  source_id      integer NOT NULL REFERENCES evidence_sources (source_id) ON DELETE CASCADE,
  claim_id       integer REFERENCES evidence_claims (claim_id) ON DELETE CASCADE,
  relation_type  text NOT NULL CHECK (relation_type IN (
                   'direct_product','ingredient','formulation','category','manufacturer_specification')),
  ingredient_id  integer REFERENCES ingredients (ingredient_id),
  formulation_id integer REFERENCES formulations (formulation_id),
  category_id    integer REFERENCES product_categories (category_id),
  relevance      numeric(4,3) CHECK (relevance IS NULL OR relevance BETWEEN 0 AND 1),
  rationale      text NOT NULL CHECK (length(btrim(rationale)) > 0),
  notes          text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT product_evidence_ingredient_ref  CHECK (relation_type <> 'ingredient'  OR ingredient_id  IS NOT NULL),
  CONSTRAINT product_evidence_formulation_ref CHECK (relation_type <> 'formulation' OR formulation_id IS NOT NULL),
  CONSTRAINT product_evidence_category_ref    CHECK (relation_type <> 'category'    OR category_id    IS NOT NULL),
  CONSTRAINT product_evidence_direct_claim    CHECK (relation_type <> 'direct_product' OR claim_id IS NOT NULL)
);
CREATE UNIQUE INDEX product_evidence_unique_idx
  ON product_evidence (product_id, source_id, COALESCE(claim_id, 0), relation_type);
CREATE INDEX product_evidence_source_idx ON product_evidence (source_id);
CREATE INDEX product_evidence_claim_idx ON product_evidence (claim_id);

