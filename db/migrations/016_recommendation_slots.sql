-- 016_recommendation_slots.sql — Evidence RAG: una recomendación principal por hueco (fase + función)
--
-- Cada recomendación Evidence RAG ocupa un hueco (consumption_timing + functional_role) y puede cubrir otros
-- huecos de la misma fase (also_covers) si el mismo producto los satisface. Guarda el objetivo derivado del claim
-- (target) y el plan de uso calculado por el servidor (usage_plan). Las alternativas del mismo hueco se guardan
-- aparte: no son recomendaciones y no cuentan en el máximo. Las recomendaciones del flujo antiguo quedan con NULL.
--
-- functional_role es una función neutra (fueling, hydration, protein_support, caffeine, supplementation) derivada
-- del nutriente y la fase; no es el rol del tipo de producto (product_type_functional_roles).

ALTER TABLE recommendations
  ADD COLUMN functional_role text
    CHECK (functional_role IN ('fueling','hydration','protein_support','caffeine','supplementation')),
  ADD COLUMN also_covers text[] NOT NULL DEFAULT '{}'
    CHECK (also_covers <@ ARRAY['fueling','hydration','protein_support','caffeine','supplementation']::text[]),
  ADD COLUMN target     jsonb,
  ADD COLUMN usage_plan jsonb,
  ADD CONSTRAINT recommendations_slot_only_evidence CHECK (
    (functional_role IS NULL AND target IS NULL AND usage_plan IS NULL AND cardinality(also_covers) = 0)
    OR evidence_mode = 'evidence_rag'),
  ADD CONSTRAINT recommendations_also_covers_not_role CHECK (
    functional_role IS NULL OR NOT (functional_role = ANY (also_covers)));

COMMENT ON COLUMN recommendations.functional_role IS
  'Evidence RAG: función del hueco (fase + función) que ocupa la recomendación. NULL en el flujo antiguo.';
COMMENT ON COLUMN recommendations.also_covers IS
  'Evidence RAG: otras funciones de la misma fase cubiertas por el mismo producto (cuenta como una sola recomendación).';

CREATE TABLE recommendation_alternatives (
  recommendation_alternative_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  recommendation_id integer NOT NULL REFERENCES recommendations (recommendation_id) ON DELETE CASCADE,
  product_id        integer NOT NULL REFERENCES products (product_id),
  rank              smallint NOT NULL CHECK (rank BETWEEN 1 AND 2),
  cadence_status    text CHECK (cadence_status IN ('cadence_verified','cadence_unverified')),
  usage_plan        jsonb,
  reason            text NOT NULL,
  created_at        timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT recommendation_alternatives_product_unique UNIQUE (recommendation_id, product_id),
  CONSTRAINT recommendation_alternatives_rank_unique UNIQUE (recommendation_id, rank)
);
CREATE INDEX recommendation_alternatives_rec_idx ON recommendation_alternatives (recommendation_id);
COMMENT ON TABLE recommendation_alternatives IS
  'Alternativas del mismo hueco (en lugar de, no además). No son recomendaciones ni cuentan en el máximo.';

-- La alternativa solo existe para recomendaciones Evidence RAG con hueco y nunca es el propio producto principal
CREATE OR REPLACE FUNCTION public.recommendation_alternatives_rules() RETURNS trigger
LANGUAGE plpgsql SET search_path = public AS $$
DECLARE
  v_product integer;
  v_role    text;
BEGIN
  SELECT product_id, functional_role INTO v_product, v_role FROM recommendations WHERE recommendation_id = NEW.recommendation_id;
  IF v_role IS NULL THEN
    RAISE EXCEPTION 'Solo una recomendación Evidence RAG con hueco funcional puede tener alternativas'
      USING ERRCODE = 'check_violation';
  END IF;
  IF v_product = NEW.product_id THEN
    RAISE EXCEPTION 'La alternativa no puede ser el producto principal (%)', NEW.product_id USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER recommendation_alternatives_rules_trg BEFORE INSERT OR UPDATE ON recommendation_alternatives
  FOR EACH ROW EXECUTE FUNCTION public.recommendation_alternatives_rules();

