-- 008_ingredients.sql
-- Normalización de ingredientes y formulaciones. Aditivo: product_nutrition.other_components NO se elimina
-- y el recomendador actual no lee estas tablas.

CREATE TABLE ingredients (
  ingredient_id  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           varchar(80) NOT NULL UNIQUE CHECK (code ~ '^[a-z0-9_]+$'),
  display_name   varchar(120) NOT NULL,
  aliases        text[] NOT NULL DEFAULT '{}',
  description    text,
  category       text NOT NULL CHECK (category IN (
                   'macronutrient','carbohydrate','protein','amino_acid','electrolyte','mineral',
                   'vitamin','stimulant','nootropic','other')),
  is_active      boolean NOT NULL DEFAULT true,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz
);
COMMENT ON TABLE ingredients IS
  'Componentes normalizados. Incluye macronutrientes (carbohydrate, protein) para enlazar guías de ingesta.';
CREATE INDEX ingredients_aliases_gin ON ingredients USING gin (aliases);
CREATE TRIGGER ingredients_set_updated_at BEFORE UPDATE ON ingredients
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE formulations (
  formulation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code           varchar(80) NOT NULL UNIQUE CHECK (code ~ '^[a-z0-9_]+$'),
  display_name   varchar(160) NOT NULL,
  description    text,
  created_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE formulation_ingredients (
  formulation_id integer NOT NULL REFERENCES formulations (formulation_id) ON DELETE CASCADE,
  ingredient_id  integer NOT NULL REFERENCES ingredients (ingredient_id),
  ratio_part     numeric(8,3) CHECK (ratio_part > 0),
  PRIMARY KEY (formulation_id, ingredient_id)
);

CREATE TABLE product_ingredients (
  product_id          integer NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
  ingredient_id       integer NOT NULL REFERENCES ingredients (ingredient_id),
  amount              numeric(12,4) CHECK (amount IS NULL OR amount >= 0),
  unit                text CHECK (unit IN ('g','mg','ug','iu','ml','ratio')),
  basis               text NOT NULL DEFAULT 'per_serving'
                        CHECK (basis IN ('per_serving','per_100g','per_unit','unspecified')),
  serving_description varchar(100),
  form                varchar(80),
  notes               text,
  data_source         text NOT NULL CHECK (data_source IN (
                        'nutrition_column','other_components','product_description',
                        'manufacturer_specification','manual')),
  source_id           integer,   -- FK a evidence_sources (especificación del fabricante); se agrega en 009
  review_status       text NOT NULL DEFAULT 'auto_confident' CHECK (review_status IN ('auto_confident','reviewed')),
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz,
  PRIMARY KEY (product_id, ingredient_id, basis),
  -- Nunca una cantidad sin unidad (no se inventan unidades)
  CHECK (amount IS NULL OR unit IS NOT NULL)
);
CREATE INDEX product_ingredients_ingredient_idx ON product_ingredients (ingredient_id);
CREATE TRIGGER product_ingredients_set_updated_at BEFORE UPDATE ON product_ingredients
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();

CREATE TABLE product_formulations (
  product_id     integer NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
  formulation_id integer NOT NULL REFERENCES formulations (formulation_id),
  data_source    text NOT NULL CHECK (data_source IN (
                   'nutrition_column','other_components','product_description',
                   'manufacturer_specification','manual')),
  notes          text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (product_id, formulation_id)
);

-- Lo ambiguo NO se inserta en product_ingredients: queda pendiente de revisión manual
CREATE TABLE ingredient_mapping_review (
  review_id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id     integer NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
  origin         text NOT NULL CHECK (origin IN ('other_components','nutrition_column','product_description')),
  raw_text       text NOT NULL,
  suggested_code varchar(80),
  reason         text NOT NULL,
  status         text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected')),
  resolved_by    varchar(255),
  resolved_at    timestamptz,
  created_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (product_id, origin, raw_text)
);
