-- 003_product_embeddings_vector.sql
-- Embeddings de productos como vector(768) (Gemini). Reemplaza el LONGTEXT JSON de MariaDB.
-- Distancia coseno: embedding <=> query  (similitud = 1 - distancia).

CREATE TABLE product_embeddings (
  embedding_id    integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  product_id      integer NOT NULL REFERENCES products (product_id) ON DELETE CASCADE,
  embedding       extensions.vector(768) NOT NULL,
  embedding_model varchar(50) DEFAULT 'text-embedding-004',
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz,
  CONSTRAINT product_embeddings_product_id_key UNIQUE (product_id),
  -- Un vector nulo (norma 0) hace que la distancia coseno sea NaN.
  CONSTRAINT product_embeddings_nonzero CHECK (extensions.vector_norm(embedding) > 0)
);
COMMENT ON COLUMN product_embeddings.embedding IS 'Vector de embeddings (768 dims, Gemini)';

CREATE INDEX product_embeddings_embedding_hnsw_idx
  ON product_embeddings USING hnsw (embedding extensions.vector_cosine_ops);

CREATE TRIGGER product_embeddings_set_updated_at
  BEFORE UPDATE ON product_embeddings
  FOR EACH ROW EXECUTE FUNCTION public.set_updated_at();
